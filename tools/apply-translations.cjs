#!/usr/bin/env node
/**
 * Merge validated translation batches into the Arabic client bundle.
 *
 * Reads every `.work/part-<n>.json` batch plus its `.work/out-<n>.json`
 * translation object, validates each pair with the same rules as
 * `check-translation-part.cjs`, and replaces the generated block between the
 * `>>> PHASE3-AR-BEGIN` / `<<< PHASE3-AR-END` markers in
 * `packages/dsh-arabic-locale/client.js` with an `AR_PHASE3` object literal.
 *
 * Entries already covered by `AR_CORE` and entries whose translation equals the
 * English source (deliberate technical tokens) are skipped. The command is
 * idempotent: running it again regenerates the block from the same inputs.
 *
 * Usage:
 *   node tools/apply-translations.cjs [--dry-run] [--parts 1,2,3]
 */
const fs = require('fs');
const path = require('path');
const { ROOT, readArCoreKeys, isTranslated } = require('./ar-keys.cjs');
const { checkPart } = require('./check-translation-part.cjs');

const CLIENT = path.join(ROOT, 'packages/dsh-arabic-locale/client.js');
const WORK = path.join(ROOT, '.work');
const BEGIN = '// >>> PHASE3-AR-BEGIN';
const END = '// <<< PHASE3-AR-END';

function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const partsArg = args.indexOf('--parts');
  const onlyParts = partsArg !== -1 ? args[partsArg + 1].split(',').map(Number) : null;
  const workArg = args.indexOf('--work');
  const WORK = workArg !== -1 ? path.resolve(args[workArg + 1]) : path.join(ROOT, '.work');
  const clientArg = args.indexOf('--client');
  const CLIENT = clientArg !== -1 ? path.resolve(args[clientArg + 1]) : path.join(ROOT, 'packages/dsh-arabic-locale/client.js');

  const manifestPath = path.join(WORK, 'manifest.json');
  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  const partNumbers = onlyParts || manifest.parts.map((part) => part.part);

  const arKeys = readArCoreKeys(CLIENT);
  const rendered = [];
  const seen = new Set();
  let total = 0;
  let skippedCore = 0;
  let skippedIdentical = 0;

  for (const partNumber of partNumbers) {
    const partPath = path.join(WORK, `part-${partNumber}.json`);
    const outPath = path.join(WORK, `out-${partNumber}.json`);
    if (!fs.existsSync(partPath) || !fs.existsSync(outPath)) {
      throw new Error(`missing batch files for part ${partNumber}: ${partPath} / ${outPath}`);
    }
    const part = JSON.parse(fs.readFileSync(partPath, 'utf8'));
    const result = checkPart(partPath, outPath);
    if (result.errors.length) {
      console.error(`part ${partNumber} failed validation:`);
      for (const error of result.errors.slice(0, 40)) console.error(`  ${error}`);
      throw new Error(`part ${partNumber}: ${result.errors.length} validation error(s)`);
    }
    const out = JSON.parse(fs.readFileSync(outPath, 'utf8'));
    const lines = [];
    for (const entry of part.entries) {
      const arabic = out[entry.en];
      if (typeof arabic !== 'string') continue;
      if (isTranslated(entry.en, arKeys)) {
        skippedCore += 1;
        continue;
      }
      if (arabic === entry.en) {
        skippedIdentical += 1;
        continue;
      }
      if (seen.has(entry.en)) continue;
      seen.add(entry.en);
      lines.push(`      ${JSON.stringify(entry.en)}: ${JSON.stringify(arabic)},`);
      total += 1;
    }
    if (lines.length) rendered.push(`      // --- ${part.name} ---`, ...lines);
    console.log(`part ${String(partNumber).padStart(2)}  ${String(lines.length).padStart(4)} entries  ${part.name}`);
  }

  const block = [
    `${BEGIN} (generated by tools/apply-translations.cjs — do not edit by hand)`,
    '    const AR_PHASE3 = {',
    ...rendered,
    '    };',
    `    ${END}`,
  ].join('\n');

  const source = fs.readFileSync(CLIENT, 'utf8');
  const beginAt = source.indexOf(BEGIN);
  const endAt = source.indexOf(END);
  if (beginAt === -1 || endAt === -1 || endAt < beginAt) throw new Error('PHASE3-AR markers not found in client.js');
  const tail = source.slice(source.indexOf('\n', endAt) + 1);
  const next = source.slice(0, beginAt) + block + '\n' + tail;

  console.log(`\nmerged entries:      ${total}`);
  console.log(`skipped (in core):   ${skippedCore}`);
  console.log(`skipped (identical): ${skippedIdentical}`);
  if (dryRun) {
    console.log('\n--dry-run: client.js not written');
    return;
  }
  fs.writeFileSync(CLIENT, next);
  console.log(`wrote ${path.relative(process.cwd(), CLIENT)}`);
}

main();
